import pandas as pd


# ----------------------------
# 1. 점수 데이터 불러오기
# ----------------------------

df = pd.read_csv(
    "data/processed/scored_mart.csv"
)

print("=== 데이터 불러오기 완료 ===")
print(df.shape)


# ----------------------------
# 2. 분위수 점수 함수
# ----------------------------
# 데이터 안에서 내가 몇 % 위치인지 계산
# 0 ~ 100점으로 변환

def percentile_score(series):
    return series.rank(
        pct=True
    ) * 100


# ----------------------------
# 3. 매출 점수
# 높을수록 좋음
# ----------------------------

df["매출점수_v2"] = percentile_score(
    df["점포당_월매출"]
)


# ----------------------------
# 4. 유동인구 점수
# 높을수록 좋음
# ----------------------------

df["유동인구점수_v2"] = percentile_score(
    df["총_유동인구_수"]
)


# ----------------------------
# 5. 2030 점수
# 높을수록 좋음
# ----------------------------

df["2030점수_v2"] = percentile_score(
    df["2030비율"]
)


# ----------------------------
# 6. 폐업 안정 점수
# 낮은 폐업비율이 높은 점수
# ----------------------------

df["폐업안정점수_v2"] = (
    100
    - percentile_score(
        df["폐업비율"]
    )
)


# ----------------------------
# 7. 최종 창업추천점수 V2
# ----------------------------

df["창업추천점수_v2"] = (
    df["매출점수_v2"] * 0.40
    + df["유동인구점수_v2"] * 0.25
    + df["2030점수_v2"] * 0.20
    + df["폐업안정점수_v2"] * 0.15
)


# ----------------------------
# 8. 점포가 너무 적은 곳 제외
# ----------------------------
# 점포 3개 이상인 경우만 추천 후보로 사용

recommend = df[
    df["점포_수"] >= 3
].copy()


# ----------------------------
# 9. 추천 순위 만들기
# ----------------------------

ranking = recommend.sort_values(
    "창업추천점수_v2",
    ascending=False
)


# ----------------------------
# 10. TOP 20 출력
# ----------------------------

print("\n=== 개선된 창업 추천 TOP 20 ===")

print(
    ranking[
        [
            "상권_코드_명",
            "서비스_업종_코드_명",
            "점포_수",
            "점포당_월매출",
            "총_유동인구_수",
            "2030비율",
            "폐업비율",
            "창업추천점수_v2"
        ]
    ].head(20).to_string(index=False)
)


# ----------------------------
# 11. 저장
# ----------------------------

df.to_csv(
    "data/processed/scored_mart_v2.csv",
    index=False,
    encoding="utf-8-sig"
)

print("\n=== 저장 완료 ===")
print("data/processed/scored_mart_v2.csv")