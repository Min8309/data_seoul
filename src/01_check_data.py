# ----------------------------
# 21. 2030 유동인구 수 계산
# ----------------------------

population["2030_유동인구_수"] = (
    population["연령대_20_유동인구_수"]
    + population["연령대_30_유동인구_수"]
)


# ----------------------------
# 22. 2030 비율 계산
